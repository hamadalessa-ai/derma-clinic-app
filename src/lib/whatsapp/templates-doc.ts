/**
 * Builds docs/WHATSAPP_TEMPLATES.md from the catalog (pnpm docs:whatsapp). A test checks the file
 * is current, so the list given to Meta always matches what the app sends.
 */
import { BUTTON_TITLES, TEMPLATE_KINDS, TEMPLATES } from "./catalog";

/** Meta writes variables as {{1}}, {{2}}… in the order of TEMPLATES[kind].variables. */
export function toMetaBody(body: string, variables: string[]) {
  return body.replace(/\{(\w+)\}/g, (m, k: string) => {
    const i = variables.indexOf(k);
    return i === -1 ? m : `{{${i + 1}}}`;
  });
}

export function buildTemplatesDoc(): string {
  const out: string[] = [
    "# WhatsApp templates to submit to Meta",
    "",
    "<!-- Generated by `pnpm docs:whatsapp` from src/lib/whatsapp/catalog.ts. Do not edit by hand. -->",
    "",
    "Real WhatsApp needs an **approved template** for every message the clinic starts (outside the",
    "24-hour window after the patient's last message). Submit each one below in Meta's",
    "**WhatsApp Manager → Message templates → Create template**, in **both languages**",
    "(Arabic `ar` and English `en`), with exactly the name shown. Variables are numbered in the order",
    "listed. Replies the clinic sends straight after a patient's message (inside 24 hours) don't need",
    "templates.",
    "",
    "Tip: if the clinic admin changes a wording in **Settings → WhatsApp messages**, submit the new",
    "wording to Meta too (live mode sends Meta's approved text).",
    "",
  ];
  for (const kind of TEMPLATE_KINDS) {
    const t = TEMPLATES[kind];
    const category = kind === "verification_code" ? "AUTHENTICATION" : "UTILITY";
    out.push(`## \`${t.metaName}\``, "");
    out.push(`- **Category:** ${category}`);
    out.push(`- **Languages:** Arabic (\`ar\`), English (\`en\`)`);
    out.push(
      `- **Variables:** ${t.variables.length ? t.variables.map((v, i) => `{{${i + 1}}} = ${v}`).join(", ") : "none"}`,
    );
    if (t.buttons.length) {
      out.push(
        `- **Quick-reply buttons:** ${t.buttons
          .map((b) => {
            const title = BUTTON_TITLES[b as keyof typeof BUTTON_TITLES];
            return `“${title.ar}” / “${title.en}”`;
          })
          .join(", ")}`,
      );
    }
    if (kind === "verification_code") {
      out.push(
        "- **Note:** Meta builds authentication templates itself (code + “copy code” button); choose",
        "  that format and the variable is the code.",
      );
    }
    out.push("", "Arabic:", "", "```text", toMetaBody(t.bodyAr, t.variables), "```", "");
    out.push("English:", "", "```text", toMetaBody(t.bodyEn, t.variables), "```", "");
  }
  return out.join("\n");
}
