/**
 * Builds db/reset.sql from the schema, so "start over" always removes EVERY table, type and
 * function that db/setup.sql creates (and nothing else). Kept in step by a test.
 */
import { readFileSync } from "node:fs";
import path from "node:path";
import { getTableName, is } from "drizzle-orm";
import { PgEnum, PgTable } from "drizzle-orm/pg-core";
import * as schema from "./schema";

const ROOT = path.resolve(__dirname, "../..");

export function schemaTables(): string[] {
  return (Object.values(schema) as unknown[])
    .filter((v) => is(v, PgTable))
    .map((t) => getTableName(t as PgTable))
    .sort();
}

export function schemaEnums(): string[] {
  return (Object.values(schema) as unknown[])
    .filter((v) => typeof v === "function" && "enumName" in (v as object))
    .map((v) => (v as unknown as PgEnum<[string, ...string[]]>).enumName)
    .sort();
}

export function sqlFunctions(): string[] {
  const names = new Set<string>();
  for (const f of ["db/booking.sql", "db/rls.sql"]) {
    const text = readFileSync(path.join(ROOT, f), "utf8");
    for (const m of text.matchAll(/create or replace function public\.([a-z_]+)\(/g))
      names.add(m[1]);
  }
  return [...names].sort();
}

/**
 * Tables that EARLIER phases created but today's schema no longer has. A live database built by an
 * older setup.sql still has them (and their policies use app_current_tenant()), so reset must drop
 * them too. tests/reset-cycle.test.ts runs reset.sql on each released setup.sql to keep this complete.
 */
export const RETIRED_TABLES = [
  "outbound_messages", // Phase 2a message log, replaced by conversations + messages in Phase 2b
];

/**
 * Safety catch: reset is for the DEMO only. It refuses (and the whole transaction rolls back,
 * changing nothing) when the database holds real patients: any patient not marked fake, or any
 * patient of a clinic that is not a demo clinic. Real clinics use the live database (src/db/live-upgrade.ts) instead.
 * FORCE RLS hides rows even from the table owner, so the check lifts FORCE for itself first —
 * inside this transaction, so a refusal undoes that too. Works on databases from older phases
 * (columns checked before use) and on an empty database.
 */
export const REAL_DATA_GUARD = `do $guard$
declare
  has_fake boolean;
  has_demo boolean;
  real_count int := 0;
begin
  if to_regclass('ops.schema_upgrades') is not null then
    raise exception 'REFUSED: this is the LIVE database (it has ops.schema_upgrades). db/reset.sql is for the demo only. Use the "Release to live" workflow instead.';
  end if;
  if to_regclass('public.patients') is null or to_regclass('public.tenants') is null then
    return;
  end if;
  select exists (select from information_schema.columns where table_schema = 'public'
                   and table_name = 'patients' and column_name = 'is_fake') into has_fake;
  select exists (select from information_schema.columns where table_schema = 'public'
                   and table_name = 'tenants' and column_name = 'is_demo') into has_demo;
  if not has_fake and not has_demo then
    return;
  end if;
  execute 'alter table public.patients no force row level security';
  execute 'alter table public.tenants no force row level security';
  execute 'select count(*) from public.patients p join public.tenants t on t.id = p.tenant_id where '
    || case when has_fake then 'not p.is_fake' else 'false' end
    || case when has_demo then ' or not t.is_demo' else '' end
    into real_count;
  if real_count > 0 then
    raise exception 'REFUSED: this database holds % real patient record(s). db/reset.sql is for the demo only and would delete them. The live system is updated by the "Release to live" workflow instead.', real_count;
  end if;
end
$guard$;`;

export function buildResetSql(): string {
  const tables = [...new Set([...schemaTables(), ...RETIRED_TABLES])]
    .sort()
    .map((t) => `public.${t}`);
  return `-- ════════════════════════════════════════════════════════════════════════════
-- DANGER: deletes ALL app tables and data (demo only) — generated by \`pnpm db:build-setup\`.
-- Paste into Supabase SQL Editor and Run, then run db/setup.sql again.
-- Does not touch anything else in the database. The clinic_app login is kept
-- (setup.sql just sets its password again).
-- ════════════════════════════════════════════════════════════════════════════
begin;
${REAL_DATA_GUARD}
drop table if exists
  ${tables.join(",\n  ")}
  cascade;
${sqlFunctions()
  .map((f) => `drop function if exists public.${f};`)
  .join("\n")}
-- Types last: functions may use them (e.g. app_set_clinic_status takes a clinic_status).
drop type if exists ${schemaEnums()
    .map((e) => `public.${e}`)
    .join(", ")};
do $$
begin
  if exists (select from pg_roles where rolname = 'clinic_app') then
    execute 'revoke all on schema public from clinic_app';
  end if;
end $$;
commit;
select 'Reset complete. Now run db/setup.sql.' as result;
`;
}
