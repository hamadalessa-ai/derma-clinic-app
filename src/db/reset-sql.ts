/**
 * Builds db/reset.sql from the schema, so "start over" always removes EVERY table, type and
 * function that db/setup.sql creates (and nothing else). Kept in step by a test.
 */
import { readFileSync } from "node:fs";
import path from "node:path";
import { getTableName, is } from "drizzle-orm";
import { PgEnum, PgTable } from "drizzle-orm/pg-core";
import * as schema from "./schema";

const ROOT = path.resolve(__dirname, "../..");

export function schemaTables(): string[] {
  return (Object.values(schema) as unknown[])
    .filter((v) => is(v, PgTable))
    .map((t) => getTableName(t as PgTable))
    .sort();
}

export function schemaEnums(): string[] {
  return (Object.values(schema) as unknown[])
    .filter((v) => typeof v === "function" && "enumName" in (v as object))
    .map((v) => (v as unknown as PgEnum<[string, ...string[]]>).enumName)
    .sort();
}

export function sqlFunctions(): string[] {
  const names = new Set<string>();
  for (const f of ["db/booking.sql", "db/rls.sql"]) {
    const text = readFileSync(path.join(ROOT, f), "utf8");
    for (const m of text.matchAll(/create or replace function public\.([a-z_]+)\(/g))
      names.add(m[1]);
  }
  return [...names].sort();
}

export function buildResetSql(): string {
  const tables = schemaTables().map((t) => `public.${t}`);
  return `-- ════════════════════════════════════════════════════════════════════════════
-- DANGER: deletes ALL app tables and data (demo only) — generated by \`pnpm db:build-setup\`.
-- Paste into Supabase SQL Editor and Run, then run db/setup.sql again.
-- Does not touch anything else in the database. The clinic_app login is kept
-- (setup.sql just sets its password again).
-- ════════════════════════════════════════════════════════════════════════════
begin;
drop table if exists
  ${tables.join(",\n  ")}
  cascade;
drop type if exists ${schemaEnums()
    .map((e) => `public.${e}`)
    .join(", ")};
${sqlFunctions()
  .map((f) => `drop function if exists public.${f};`)
  .join("\n")}
do $$
begin
  if exists (select from pg_roles where rolname = 'clinic_app') then
    execute 'revoke all on schema public from clinic_app';
  end if;
end $$;
commit;
select 'Reset complete. Now run db/setup.sql.' as result;
`;
}
